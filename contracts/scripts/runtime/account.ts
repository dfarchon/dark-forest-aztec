/**
 * Account runtime checks and append-only writes to networks/<name>.env.
 */
import { getSchnorrInitializerlessAccountContractAddress } from '@aztec/accounts/schnorr';
import { Fq, Fr } from '@aztec/aztec.js/fields';
import fs from 'fs';
import path from 'path';

import { getNetworkValue, loadNetworkEnv, reloadNetworkEnv } from './env.ts';
import { requireNetworkConfigured } from './network.ts';

export const ACCOUNT_KEYS = [
    'ACCOUNT_SALT',
    'ACCOUNT_SECRET_KEY',
    'ACCOUNT_SIGNING_KEY',
    'ACCOUNT_ADDRESS',
] as const;

export type AccountKey = (typeof ACCOUNT_KEYS)[number];

export type AccountDiagnosis = {
    ok: boolean;
    present: AccountKey[];
    missing: AccountKey[];
    address: string | undefined;
};

export type GeneratedAccountKeys = {
    salt: string;
    secretKey: string;
    signingKey: string;
    address: string;
};

function fqToHex(signingKey: Fq): string {
    return signingKey.toBuffer().toString('hex');
}

export function diagnoseAccount(): AccountDiagnosis {
    const present = ACCOUNT_KEYS.filter((key) => getNetworkValue(key));
    const missing = ACCOUNT_KEYS.filter((key) => !getNetworkValue(key));
    return {
        ok: missing.length === 0,
        present,
        missing,
        address: getNetworkValue('ACCOUNT_ADDRESS'),
    };
}

export function requireAccountConfigured(): void {
    requireNetworkConfigured();
    const diagnosis = diagnoseAccount();
    if (diagnosis.ok) return;

    const ctx = loadNetworkEnv();
    const rel = path.relative(process.cwd(), ctx.networkFilePath);
    const lines = [
        '\nAccount is not configured.',
        `  Network: ${ctx.network}`,
        `  Config:  ${rel}`,
        `  Present: ${diagnosis.present.length ? diagnosis.present.join(', ') : '(none)'}`,
        `  Missing: ${diagnosis.missing.join(', ')}`,
        '  Generate keys with:',
        '    pnpm account:generate',
        '',
    ];
    console.error(lines.join('\n'));
    process.exit(1);
}

export async function generateAccountKeys(): Promise<GeneratedAccountKeys> {
    const salt = Fr.random();
    const secretKey = Fr.random();
    const signingKey = Fq.random();
    const address = await getSchnorrInitializerlessAccountContractAddress(
        signingKey,
        salt,
        secretKey
    );
    return {
        salt: salt.toString(),
        secretKey: secretKey.toString(),
        signingKey: fqToHex(signingKey),
        address: address.toString(),
    };
}

/**
 * Append ACCOUNT_* at the end of the active networks/*.env.
 * Does not edit or delete any existing line.
 */
export function appendAccountToNetworkEnv(
    keys: GeneratedAccountKeys,
    generatedAt: string = new Date().toISOString()
): void {
    const ctx = loadNetworkEnv();
    const existing = fs.readFileSync(ctx.networkFilePath, 'utf-8');
    const prefix = existing.length === 0 || existing.endsWith('\n') ? '' : '\n';
    const block = [
        '',
        '# Generated by pnpm account:generate',
        `# Network: ${ctx.network}`,
        `# Generated at: ${generatedAt}`,
        '# Appended only; earlier lines in this file were not changed.',
        `ACCOUNT_SALT=${keys.salt}`,
        `ACCOUNT_SECRET_KEY=${keys.secretKey}`,
        `ACCOUNT_SIGNING_KEY=${keys.signingKey}`,
        `ACCOUNT_ADDRESS=${keys.address}`,
        '',
    ].join('\n');

    fs.appendFileSync(ctx.networkFilePath, prefix + block);
    reloadNetworkEnv();
}
