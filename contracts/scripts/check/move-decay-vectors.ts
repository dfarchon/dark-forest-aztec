/**
 * Generate the move decay comparison table for
 * tests/high_level_planet/src/move_decay_vectors.nr.
 *
 * The frontend predicts how much energy a move delivers with `decayedPopArriving`
 * in client/src/Session/TxExecutor/MoveSimulation.ts. The Move contract decides
 * with `decayed_pop_arriving` in libs/src/move_decay.nr. If the two disagree, the
 * UI offers a move that reverts on chain ("Not enough forces to make move").
 *
 * This script runs the client function over a fixed grid of energy caps, ranges,
 * send shares, and distances, and writes each input with the client's result.
 * The Noir test `move_decay::matches_client_vectors` in tests/high_level_planet
 * asserts the contract returns the same numbers, and client/tests/moveDecay.test.ts
 * reads the same file.
 *
 * Run from contracts:
 *   pnpm test:decay-match              (verify the table is current, then run Noir tests)
 *   pnpm test:decay-match:regenerate   (rewrite the table after an intended formula change)
 */
import fs from 'fs';
import path from 'path';

import { decayedPopArriving } from '../../../client/src/Session/TxExecutor/MoveSimulation.ts';
import { formatNoir } from './noir-format.ts';

const CONTRACTS_ROOT = path.resolve(import.meta.dirname, '..', '..');
const OUTPUT = path.join(
    CONTRACTS_ROOT,
    'tests',
    'high_level_planet',
    'src',
    'move_decay_vectors.nr'
);

// Energy caps in contract units (UI energy * 1000).
const CAPS: bigint[] = [
    100_000n, // level 0
    6_000_000n, // level 3
    700_000_000n, // level 8
    1_209_600_000n, // level 8, nebula, rank 3 (player report)
    2_419_200_000n, // level 8, dead space, rank 3 (above 2^31)
    7_962_624_000n, // level 9, all boosts, dead space, rank 5
    16_000_000_000n, // level 9 silver bank, all boosts, dead space
];

const RANGES: bigint[] = [
    99n, // smallest level 0 range
    6_306n, // level 8
    86_221n, // level 9, all boosts, dead space, four range upgrades
];

// Send share in basis points of the cap, around each bend of the curve and the old 1% cutoff.
const SHARES_BP: bigint[] = [
    1n,
    10n,
    99n,
    100n,
    101n,
    2_500n,
    2_501n,
    5_000n,
    5_001n,
    10_000n,
];

/** Distances (times hundred) relative to L * 100 = range * 432. */
function distances(range: bigint): bigint[] {
    const l = range * 432n;
    return [0n, 1n, 100n, l / 4n, l / 2n, (l * 3n) / 4n, l - 1n, l, l * 2n];
}

type Row = [bigint, bigint, bigint, bigint, bigint];

function rows(): Row[] {
    const result: Row[] = [];
    for (const cap of CAPS) {
        for (const range of RANGES) {
            for (const bp of SHARES_BP) {
                const pop = (cap * bp) / 10_000n;
                for (const dist of distances(range)) {
                    result.push([
                        pop,
                        cap,
                        range,
                        dist,
                        decayedPopArriving(pop, cap, range, dist),
                    ]);
                }
            }
        }
    }
    return result;
}

function generate(): string {
    const table = rows();
    return formatNoir(
        [
            '// Generated by scripts/check/move-decay-vectors.ts. Do not edit.',
            '// Each row: (pop_moved, population_cap, range, effective_dist_times_hundred, client result).',
            '// The client result comes from decayedPopArriving in client/src/Session/TxExecutor/MoveSimulation.ts.',
            `pub global MOVE_DECAY_VECTORS: [(u128, u128, u128, u128, u128); ${table.length}] = [`,
            ...table.map((row) => `    (${row.join(', ')}),`),
            '];',
            '',
        ].join('\n')
    );
}

function main() {
    const check = process.argv.includes('--check');
    const output = generate();
    const relOutput = path.relative(process.cwd(), OUTPUT);
    const exists = fs.existsSync(OUTPUT);
    const current = exists ? fs.readFileSync(OUTPUT, 'utf-8') : '';

    if (check) {
        if (!exists) {
            console.error(
                [
                    `${relOutput} does not exist yet.`,
                    'Generate it once with `pnpm test:decay-match:regenerate`, review it, and commit it.',
                ].join('\n')
            );
            process.exit(1);
        }
        if (current !== output) {
            console.error(
                [
                    `${relOutput} no longer matches the client's decayedPopArriving.`,
                    '',
                    'The frontend move decay formula (or the grid in this script) changed since the',
                    'table was generated. If the formula change is intended:',
                    '  1. Run `pnpm test:decay-match:regenerate` and review the diff.',
                    '  2. Change libs/src/move_decay.nr until `pnpm test:decay-match` passes.',
                    'If it is not intended, revert the change in client/src/Session/TxExecutor/MoveSimulation.ts.',
                ].join('\n')
            );
            process.exit(1);
        }
        console.log(`Move decay table is up to date (${rows().length} rows).`);
        return;
    }

    fs.writeFileSync(OUTPUT, output);
    console.log(
        [
            current === output
                ? `${relOutput} is unchanged.`
                : `Wrote ${relOutput}.`,
            'Next: run `pnpm test:decay-match` to confirm the contract returns the same numbers,',
            'then commit the file.',
        ].join('\n')
    );
}

main();
